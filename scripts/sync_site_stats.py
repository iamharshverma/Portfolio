#!/usr/bin/env python3
"""
scripts/sync_site_stats.py
===========================
Single source of truth synchronizer for Harsh Verma's portfolio metrics.
Ensures research paper counts, awards counts, book counts, patents,
media features, and verified profile metrics remain uniform, accurate,
and up-to-date across all HTML pages, templates, scripts, and server code.

Usage:
    python3 scripts/sync_site_stats.py
"""

import os
import re
import json

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load_canonical_stats():
    # 1. Papers count from papers_data.json
    papers_path = os.path.join(ROOT_DIR, "papers_data.json")
    if os.path.exists(papers_path):
        with open(papers_path, "r", encoding="utf-8") as f:
            papers = json.load(f)
            papers_count = len(papers)
    else:
        papers_count = 25

    # 2. Awards count from awards_data.json
    awards_path = os.path.join(ROOT_DIR, "awards_data.json")
    if os.path.exists(awards_path):
        with open(awards_path, "r", encoding="utf-8") as f:
            awards = json.load(f)
            awards_count = len(awards)
    else:
        awards_count = 27

    # 3. Media items count from media_data.json
    media_path = os.path.join(ROOT_DIR, "media_data.json")
    if os.path.exists(media_path):
        with open(media_path, "r", encoding="utf-8") as f:
            media = json.load(f)
            media_count = len(media)
    else:
        media_count = 40

    # 4. Verified profiles count from page-about.html
    about_path = os.path.join(ROOT_DIR, "page-about.html")
    if os.path.exists(about_path):
        with open(about_path, "r", encoding="utf-8") as f:
            about_html = f.read()
        profiles_count = len(re.findall(r'class="[^"]*profile-card-item', about_html))
    else:
        profiles_count = 57

    # 5. Additional section counts from data JSONs / HTML
    data_dir = os.path.join(ROOT_DIR, "data")
    def read_json_len(rel_path, key=None, fallback=0):
        p = os.path.join(data_dir, rel_path)
        if os.path.exists(p):
            try:
                with open(p, "r", encoding="utf-8") as f:
                    d = json.load(f)
                if key and isinstance(d, dict):
                    return len(d.get(key, []))
                if isinstance(d, list):
                    return len(d)
            except Exception:
                pass
        return fallback

    associations_count = read_json_len("memberships_and_associations.json", fallback=28)
    judging_count = read_json_len("judging_engagements.json", fallback=25)
    speaking_count = read_json_len("speaking_engagements.json", fallback=12)
    blogs_count = read_json_len("blog_articles.json", fallback=31)
    projects_count = read_json_len("projects_certification.json", key="projects", fallback=13)
    certifications_count = read_json_len("projects_certification.json", key="certifications", fallback=24)
    slides_decks = read_json_len("slides.json", key="decks", fallback=10)
    social_posts_count = read_json_len("social_posts.json", fallback=12)

    slides_total = 169
    slides_path = os.path.join(data_dir, "slides.json")
    if os.path.exists(slides_path):
        try:
            with open(slides_path, "r", encoding="utf-8") as f:
                slides_total = int(json.load(f).get("total_slides", 169))
        except Exception:
            pass

    videos_count = 10
    total_engagements = judging_count + speaking_count + videos_count

    return {
        "papers_count": papers_count,
        "papers_display": f"{papers_count}+",
        "awards_count": awards_count,
        "awards_display": f"{awards_count}",
        "awards_display_plus": f"{awards_count}+",
        "books_count": 2,
        "books_reviewed": 6,
        "patents_count": 7,
        "patents_display_plus": "7+",
        "media_count": media_count,
        "media_display": f"{media_count}+",
        "profiles_count": profiles_count,
        "profiles_display": f"{profiles_count}",
        "associations_count": associations_count,
        "associations_display_plus": f"{associations_count}+",
        "judging_count": judging_count,
        "judging_display_plus": f"{judging_count}+",
        "speaking_count": speaking_count,
        "videos_count": videos_count,
        "total_engagements": total_engagements,
        "total_engagements_plus": f"{total_engagements}+",
        "blogs_count": blogs_count,
        "projects_count": projects_count,
        "certifications_count": certifications_count,
        "portfolio_total": projects_count + certifications_count,
        "slides_decks": slides_decks,
        "slides_total": slides_total,
        "social_posts_count": social_posts_count,
    }

